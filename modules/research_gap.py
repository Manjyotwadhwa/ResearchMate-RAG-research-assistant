"""EXPERIMENTAL: suggest research gaps across papers.

Everything under "unexplored areas" and "future research questions" is a
hypothesis generated by an LLM, not a verified discovery. The prompt enforces
that labelling and the UI repeats it.
"""

from __future__ import annotations

from langchain_core.language_models import BaseChatModel

from config.settings import Settings
from modules.rag_pipeline import AnalysisResult, run_document_analysis
from modules.vector_store import DocumentIndex
from utils.prompts import GAP_PROMPT, GAP_QUERIES

GAP_DISCLAIMER = (
    "Experimental feature. Suggested gaps are hypotheses for further investigation, "
    "not verified scientific findings. Check them against the literature before relying on them."
)


def analyze_research_gaps(
    index: DocumentIndex,
    llm: BaseChatModel | None,
    paper_names: list[str],
    settings: Settings,
) -> AnalysisResult:
    """Identify shared areas, conflicts, stated limitations and hypothesised gaps."""
    unique_names = list(dict.fromkeys(paper_names))
    if len(unique_names) < 2:
        return AnalysisResult("Research gap analysis", "", error="Select at least two different papers.")
    return run_document_analysis(
        index=index,
        llm=llm,
        sources=unique_names,
        queries=GAP_QUERIES,
        prompt=GAP_PROMPT,
        title="Research gap analysis (experimental)",
        settings=settings,
        per_query_k=2,
    )
